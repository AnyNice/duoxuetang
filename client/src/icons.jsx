export function Icon({ name, size = 16, filled = false, className = '' }) {
  return (
    <svg
      className={`icon ${className}`}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? 'currentColor' : 'none'}
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name] || null}
    </svg>
  );
}

// 练习判分标记：图标 + 文字，按结论配色（答全了绿 / 答到一部分黄 / 没答到红）
const VERDICT_META = {
  full: { icon: 'check-circle', label: '答全了' },
  partial: { icon: 'circle-dot', label: '答到一部分' },
  miss: { icon: 'x-circle', label: '没答到' },
};

export function VerdictTag({ verdict, size = 15 }) {
  const meta = VERDICT_META[verdict];
  if (!meta) return <span>{verdict}</span>;
  return (
    <span className={`verdict verdict-${verdict}`}>
      <Icon name={meta.icon} size={size} />
      {meta.label}
    </span>
  );
}
